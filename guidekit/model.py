class Calendar(Component):
    title: str | None = None
    days: list[str]
    rows: list[str]  # row labels
    cells: list[str]  # one string per row, one char per day; "." = rest
    legend: dict[str, str]  # char → label

    @model_validator(mode="after")
    def _grid(self) -> "Calendar":
        if len(self.cells) != len(self.rows):
            raise ValueError(f"calendar has {len(self.rows)} rows but {len(self.cells)} cell strings")
        for i, row in enumerate(self.cells):
            if len(row) != len(self.days):
                raise ValueError(f"calendar row {i + 1} has {len(row)} cells, expected {len(self.days)}")
            for ch in row:
                if ch != "." and ch not in self.legend:
                    raise ValueError(f"calendar cell {ch!r} missing from legend")
        return self


