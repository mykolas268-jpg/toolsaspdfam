class BlockBase(Strict):
    kind: ClassVar[str]

    @property
    def body(self) -> Component:
        return getattr(self, self.kind)


def _make_block(kind: str, comp: type[Component]) -> type[BlockBase]:
    cls = create_model(f"{comp.__name__}Block", __base__=BlockBase, **{kind: (comp, ...)})
    cls.kind = kind
    return cls


_BLOCK_MODELS = {k: _make_block(k, v) for k, v in BLOCK_TYPES.items()}


def _block_kind(v: Any) -> str | None:
    if isinstance(v, BlockBase):
        return v.kind
    if isinstance(v, dict) and len(v) == 1:
        key = next(iter(v))
        return key if key in _BLOCK_MODELS else None
    return None


Block = Annotated[
    Union[tuple(Annotated[m, Tag(k)] for k, m in _BLOCK_MODELS.items())],  # type: ignore[misc]
    Discriminator(_block_kind),
]


# --------------------------------------------------------------------------- pages

PageType = Literal[
    "cover", "short_version", "at_a_glance", "tags_safety", "section_opener", "ladder",
    "head_to_head", "plan", "myths", "story", "checklist", "next_step", "sources",
]
PAGE_TYPES: tuple[str, ...] = PageType.__args__  # type: ignore[attr-defined]


class Page(Strict):
    type: PageType
    kicker: str | None = None
    title: str | None = None
    lede: Line | None = None
    section_number: str | None = None  # section_opener
    image: SlotId | None = None  # cover hero
    badge: str | None = None  # cover
    footer_note: str | None = None
    blocks: list[Block] = Field(default_factory=list)

    # filled by the loader, not from YAML
    id: str = Field(default="", exclude=True)
    file: str = Field(default="", exclude=True)

    @model_validator(mode="after")
    def _required(self) -> "Page":
        if self.type not in ("cover", "sources") and not self.title:
            raise ValueError(f"page type {self.type!r} needs a title")
        if self.type == "section_opener" and not self.section_number:
            raise ValueError("section_opener pages need section_number")
        return self
