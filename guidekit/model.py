class ClaimLine(Strict):
    claim: ClaimId
    text: str | None = None  # display wording; defaults to claim.text


class EditorialLine(Strict):
    editorial: Literal[True]
    text: str
    implicit: bool = Field(default=False, exclude=True)  # came from a component-level editorial flag


PlaceholderKind = Literal["creator", "photo", "cta", "confirm"]


class PlaceholderLine(Strict):
    placeholder: PlaceholderKind
    prompt: str
    label: str | None = None  # short title shown in the box
    draft: str | None = None  # confirm: what the brief says, awaiting approval


class BareLine(Strict):
    """A plain string where a tagged line was required. Always a lint failure
    unless the enclosing component sets `editorial: true`."""
    text: str


def _line_kind(v: Any) -> str | None:
    if isinstance(v, str):
        return "bare"
    if isinstance(v, dict):
        for key in ("claim", "editorial", "placeholder"):
            if key in v:
                return key
        if set(v) == {"text"}:
            return "bare"
        return None
    return {
        ClaimLine: "claim", EditorialLine: "editorial",
        PlaceholderLine: "placeholder", BareLine: "bare",
    }.get(type(v))


def _to_bare(v: Any) -> Any:
    return {"text": v} if isinstance(v, str) else v


Line = Annotated[
    Union[
        Annotated[ClaimLine, Tag("claim")],
        Annotated[EditorialLine, Tag("editorial")],
        Annotated[PlaceholderLine, Tag("placeholder")],
        Annotated[BareLine, BeforeValidator(_to_bare), Tag("bare")],
    ],
    Discriminator(_line_kind),
]
LINE_TYPES = (ClaimLine, EditorialLine, PlaceholderLine, BareLine)


class Component(Strict):
    """Base for block bodies. `editorial: true` marks every bare string inside the
    component as editorial (instructions/opinion) so tables stay readable."""
    editorial: bool = False

    @model_validator(mode="after")
    def _promote_bare(self) -> "Component":
        if self.editorial:
            _promote(self)
        return self


def _promote(obj: Any) -> Any:
    if isinstance(obj, BareLine):
        return EditorialLine(editorial=True, text=obj.text, implicit=True)
    if isinstance(obj, list):
        for i, item in enumerate(obj):
            obj[i] = _promote(item)
        return obj
    if isinstance(obj, BaseModel):
        for name in type(obj).model_fields:
            val = getattr(obj, name)
            new = _promote(val)
            if new is not val:
                object.__setattr__(obj, name, new)
        return obj
    return obj


