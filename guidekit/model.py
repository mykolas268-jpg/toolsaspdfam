class RangeRow(Strict):
    label: str
    claim: ClaimId | None = None
    lo: float | None = None
    hi: float | None = None
    no_data: ClaimId | None = None  # an N claim; renders a NO DATA row, never a bar

    @model_validator(mode="after")
    def _shape(self) -> "RangeRow":
        if self.no_data:
            if self.claim or self.lo is not None or self.hi is not None:
                raise ValueError("a no_data row cannot carry a claim or lo/hi values")
        elif not (self.claim and self.lo is not None and self.hi is not None):
            raise ValueError("a range row needs claim, lo and hi (or no_data)")
        elif self.lo > self.hi:
            raise ValueError("lo must be <= hi")
        return self


